export function translateDashboardText(
  language: DashboardLanguage,
  source: string,
  values: TranslationValues = {},
): string {
  const interpolate = (template: string) => template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );

  if (language === "pt") {
    const chinese = translations[source]?.zh;
    const portuguese = interpolate(translations[source]?.pt ?? source);

    // Some operational labels already include their official Chinese name
    // (for example, J&T 重点保障). Repeating it as a second translation makes
    // headings difficult to scan, so those labels remain a single, clean line.
    if (!chinese || /[\u3400-\u9fff]/.test(portuguese)) return portuguese;

    // Keep the Portuguese interface stable here. Visual bilingual components
    // can opt in without mutating the rendered React tree.
    return portuguese;
  }

  return interpolate(translations[source]?.[language] ?? source);
}

export function bilingualDashboardText(
  source: string,
  values: TranslationValues = {},
): BilingualDashboardText {
  const interpolate = (template: string) => template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );
  const portuguese = interpolate(source);
  const mandarin = translations[source]?.zh ? interpolate(translations[source].zh) : null;

  return {
    portuguese,
    // Do not repeat official labels that already contain their Mandarin name.
    mandarin: /[\u3400-\u9fff]/.test(portuguese) ? null : mandarin,
  };
}

export function dashboardHtmlLang(language: DashboardLanguage): string {
  return DASHBOARD_LANGUAGES.find((option) => option.code === language)?.htmlLang ?? "pt-BR";
}

export function dashboardLocale(language: DashboardLanguage): string {
  if (language === "en") return "en-US";
  if (language === "zh") return "zh-CN";
  return "pt-BR";
}

export function isDashboardLanguage(value: unknown): value is DashboardLanguage {
  return value === "pt" || value === "en" || value === "zh";
}
